def _inp(label, hint='', itype='number', unit=None):
    """Поле ввода метрики. Порядок полей задаёт порядок аргументов формулы."""
    d = {'label': label, 'hint': hint, 'type': itype}
    if unit:
        d['unit'] = unit
    return d


def _m(mid, question, inputs, formula, calc_type, responsible,
       threshold, comparison, note):
    """Сборка метрики в формате, который рендерит SalesBrief.tsx."""
    return {
        'id': mid, 'question': question, 'inputs': inputs, 'formula': formula,
        'calc_type': calc_type, 'responsible': responsible,
        'health_threshold': threshold, 'health_comparison': comparison,
        'health_note': note,
    }


