# Реестр всех профильных брифов (кроме medium — он эталон в get_brief_questions)
PROFILE_BRIEFS = {
    'startup': _STARTUP,
    'micro': _MICRO,
    'small': _SMALL,
    'small_medium': _SMALL_MEDIUM,
}

# Эталонные (medium) функциональные брифы — «голые» ключи в get_brief_questions
MEDIUM_BRIEF_TYPES = ['sales', 'marketing', 'service', 'resources',
                      'finance', 'hr', 'it', 'quality']
# Качественные брифы, общие для всех профилей
COMMON_BRIEF_TYPES = ['briefing', 'point_a', 'docs']

# Профильные качественные брифы (доп. к метрик-брифам конкретного профиля).
# FFE — для стартапа: запуск с нуля, где метрик «До» ещё нет.
PROFILE_EXTRA_BRIEFS = {
    'startup': ['ffe'],
}


def _brief_meta(brief_type: str) -> dict:
    """Краткая карточка брифа (имя/описание) для каталога на фронте."""
    q = get_brief_questions(brief_type)
    metrics = q.get('metrics') or []
    if metrics:
        desc = f'{len(metrics)} метрик · функциональная зрелость и точки роста'
    else:
        desc = q.get('desc') or 'Качественная анкета'
    return {
        'type': brief_type,
        'name': q.get('title', brief_type),
        'count': len(metrics),
        'desc': desc,
    }


def list_brief_types_for_size(size: str) -> list[dict]:
    """Брифы, доступные для профиля размера (для модалки создания).

    Сначала профильные качественные брифы (PROFILE_EXTRA_BRIEFS, напр. FFE у
    стартапа), затем метрик-брифы профиля.
    """
    if size == 'medium' or not size:
        types = MEDIUM_BRIEF_TYPES
    else:
        types = [b['type'] for b in PROFILE_BRIEFS.get(size, {}).values()]
    types = list(PROFILE_EXTRA_BRIEFS.get(size, [])) + types
    return [_brief_meta(t) for t in types]


def brief_catalog() -> dict:
    """Единый каталог для фронта: профили + брифы каждого размера + общие.

    Заменяет хардкод BRIEF_NAMES/BRIEF_DESCS на фронте.
    """
    return {
        'profiles': PROFILES,
        'briefs_by_size': {
            p['key']: list_brief_types_for_size(p['key']) for p in PROFILES
        },
        'common': [_brief_meta(t) for t in COMMON_BRIEF_TYPES],
    }


