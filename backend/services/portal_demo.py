def is_demo_doc(doc_id: int) -> bool:
    return _DEMO_DOC_BASE < doc_id <= _DEMO_DOC_BASE + 999


def _demo_doc_by_id(doc_id: int) -> dict | None:
    for doc in demo_documents():
        if doc["id"] == doc_id:
            return doc
    return None


def demo_document_pdf(doc_id: int) -> tuple[str, str, bytes] | None:
    """(filename, content_type, bytes) для скачивания демо-документа или None."""
    doc = _demo_doc_by_id(doc_id)
    if doc is None:
        return None
    pdf = _minimal_pdf([
        "SHEF - client portal (demo)",
        "",
        doc["title"],
        "",
        "This is a placeholder document for the portal demo.",
        "Real project files appear here for actual clients.",
    ])
    return doc["original_filename"], "application/pdf", pdf


def _minimal_pdf(lines: list[str]) -> bytes:
    """Минимальный валидный одностраничный PDF (шрифт Helvetica, latin-текст).

    Кириллица в базовом шрифте не рендерится, поэтому заглушка на латинице —
    для демо этого достаточно (файл открывается и не «битый»)."""
    def esc(s: str) -> str:
        return s.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")

    body = ["BT", "/F1 16 Tf", "72 770 Td", "20 TL"]
    for i, line in enumerate(lines):
        if i:
            body.append("T*")
        body.append(f"({esc(line)}) Tj")
    body.append("ET")
    stream = "\n".join(body).encode("latin-1", "replace")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
        b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
    ]

    out = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for i, obj in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + obj + b"\nendobj\n"
    xref_pos = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode()
    out += b"0000000000 65535 f \n"
    for off in offsets[1:]:
        out += f"{off:010d} 00000 n \n".encode()
    out += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
        f"startxref\n{xref_pos}\n%%EOF"
    ).encode()
    return bytes(out)
