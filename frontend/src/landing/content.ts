/** Тип-гард для «простого объекта» (не массив, не null). */
function isPlainObject(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

/**
 * Глубоко сливает сохранённый контент поверх дефолта.
 *  - примитивы и массивы из override заменяют дефолт целиком;
 *  - вложенные объекты сливаются рекурсивно;
 *  - ключи, которых нет в override, берутся из дефолта (устойчиво к старым
 *    сохранениям и к добавлению новых полей в будущем).
 * Возвращает НОВЫЙ объект типа LandingContent — БД-данные не доверяем как есть.
 */
export function mergeLandingContent(
  base: LandingContent,
  override: unknown,
): LandingContent {
  return deepMerge(base as unknown as Record<string, unknown>, override) as unknown as LandingContent;
}

function deepMerge(base: unknown, override: unknown): unknown {
  if (override === undefined || override === null) return base;
  if (isPlainObject(base) && isPlainObject(override)) {
    const out: Record<string, unknown> = { ...base };
    for (const key of Object.keys(base)) {
      if (key in override) out[key] = deepMerge(base[key], override[key]);
    }
    return out;
  }
  // Для массивов и примитивов: берём override, но только если тип совпадает с
  // дефолтом (иначе — оставляем дефолт, чтобы кривые данные не сломали рендер).
  if (Array.isArray(base)) return Array.isArray(override) ? override : base;
  if (typeof base === typeof override) return override;
  return base;
}
