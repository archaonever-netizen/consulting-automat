function getStakeholderMethodStatus(stakeholder: StakeholderCard) {
  const requiredValues = [
    stakeholder.role,
    stakeholder.type,
    stakeholder.details,
    stakeholder.need,
    stakeholder.value,
    stakeholder.resultCriterion,
    stakeholder.verificationMethod,
    stakeholder.dataSource,
  ];
  const filledCount = requiredValues.filter(value => value.trim().length > 0).length;

  if (filledCount === 0) return 'не заполнен';
  if (stakeholder.details.trim().length > 0 && !stakeholder.details.includes('/') && stakeholder.details.trim().split(/\s+/).length < 2) {
    return 'есть методологическая ошибка';
  }
  if (shouldShowStakeholderSegment(stakeholder.role) && getStakeholderSegmentValue(stakeholder).length === 0) {
    return 'заполнен частично';
  }
  if (filledCount === requiredValues.length) return 'валиден';
  return 'заполнен частично';
}

function getCompetencyGap(competency: CompetencyCard) {
  if (!competency.currentLevel || !competency.requiredLevel) return 'не рассчитан';
  const current = competencyLevelScores[competency.currentLevel];
  const required = competencyLevelScores[competency.requiredLevel];
  if (current === undefined || required === undefined) return 'не рассчитан';
  const gap = required - current;
  if (gap <= 0) return 'разрыва нет';
  if (gap === 1) return 'малый разрыв';
  if (gap === 2) return 'средний разрыв';
  return 'критический разрыв';
}

