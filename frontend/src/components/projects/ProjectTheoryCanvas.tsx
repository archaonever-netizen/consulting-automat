function getConstraintMethodStatus(constraint: ConstraintCard) {
  const hasRelation = constraint.resultCriterion.trim().length > 0 || constraint.hypothesis.trim().length > 0 || constraint.scope.trim().length > 0;
  const requiredValues = [
    constraint.type,
    constraint.subtype,
    constraint.statement,
    constraint.rigidity,
    constraint.limit,
    constraint.direction,
    constraint.scope,
    constraint.violationConsequence,
    constraint.owner,
    constraint.controlSource,
    constraint.controlFrequency,
  ];
  const filledCount = requiredValues.filter(value => value.trim().length > 0).length;

  if (filledCount === 0) return 'не заполнено';
  if (isHypotheticalConstraint(constraint) && !constraint.hypothesis.trim()) return 'заполнено частично';
  if (!hasRelation) return 'есть методологическая ошибка';
  if (filledCount === requiredValues.length && hasRelation) return 'валидно';
  return 'заполнено частично';
}

function getQualityMetricDependencies(dependency: QualityDependency | undefined, selectedDefects: string[]) {
  if (!dependency) return [];

  const defects = selectedDefects.length
    ? dependency.defects.filter(defect => selectedDefects.includes(defect.type))
    : dependency.defects;

  return defects.flatMap(defect => defect.metrics);
}

